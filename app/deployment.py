"""
Deployment metadata loader and formatter.
Reads dynamic deployment metadata generated by CI/CD and Puppet.
Never hardcodes deployment status or credentials.
"""

from datetime import datetime, timezone, timedelta, tzinfo
import json
import os
from typing import Any, Dict, Optional

# Fixed IST timezone offset (UTC+5:30) for guaranteed consistent rendering
IST_OFFSET = timezone(timedelta(hours=5, minutes=30))
IST_TZ: tzinfo

try:
    from zoneinfo import ZoneInfo
    IST_TZ = ZoneInfo("Asia/Kolkata")
except Exception:  # pragma: no cover
    IST_TZ = IST_OFFSET

DEFAULT_MESSAGE = (
    "Successfully deployed through CI/CD pipeline. Puppet Agent pulled and "
    "applied the latest configuration from Puppet Master."
)
DEFAULT_PATH = "GitHub Actions → GHCR → Puppet Master → Puppet Agent"
DEFAULT_PIPELINE = "GitHub Actions"


def _format_ist(dt: datetime) -> str:
    """Convert a UTC or aware datetime to Asia/Kolkata (IST) string."""
    try:
        ist_dt = dt.astimezone(IST_TZ)
    except Exception:
        ist_dt = dt.astimezone(IST_OFFSET)
    # Format e.g. "18 Nov 2026, 08:15 PM IST"
    return ist_dt.strftime("%d %b %Y, %I:%M %p IST")


def parse_timestamp_to_ist(timestamp_str: Optional[str]) -> tuple[str, str]:
    """
    Parse an ISO-8601 UTC timestamp and return (formatted_ist, raw_utc).
    Gracefully handles invalid or missing timestamps.
    """
    if not timestamp_str:
        now_utc = datetime.now(timezone.utc)
        return _format_ist(now_utc), now_utc.strftime("%Y-%m-%d %H:%M:%S UTC")

    clean_str = timestamp_str.strip()
    # Normalize trailing Z to +00:00 for fromisoformat
    if clean_str.endswith("Z"):
        clean_str = clean_str[:-1] + "+00:00"

    try:
        dt = datetime.fromisoformat(clean_str)
        if dt.tzinfo is None:
            dt = dt.replace(tzinfo=timezone.utc)
        formatted_ist = _format_ist(dt)
        raw_utc = dt.astimezone(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
        return formatted_ist, raw_utc
    except Exception:
        now_utc = datetime.now(timezone.utc)
        return _format_ist(now_utc), clean_str


def get_deployment_metadata_path() -> str:
    """Return the filesystem path to the deployment metadata JSON file."""
    explicit_path = os.environ.get("DEPLOYMENT_METADATA_FILE")
    if explicit_path:
        return explicit_path

    # Standard container mount path
    container_path = "/app/data/deployment.json"
    if os.path.exists(container_path):
        return container_path

    # Local development / workspace relative path
    base_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    local_data_path = os.path.join(base_dir, "data", "deployment.json")
    if os.path.exists(local_data_path):
        return local_data_path

    return container_path


def load_deployment_metadata() -> Dict[str, Any]:
    """
    Read the latest successful deployment metadata from disk or environment.
    Guarantees a clean, structured dictionary even if the file is missing or corrupted.
    """
    metadata: Dict[str, Any] = {}
    path = get_deployment_metadata_path()

    if os.path.exists(path):
        try:
            with open(path, "r", encoding="utf-8") as f:
                data = json.load(f)
                if isinstance(data, dict):
                    metadata = data
        except Exception:
            metadata = {}

    # Read values with fallbacks to environment variables then defaults
    status = (
        metadata.get("deployment_status")
        or os.environ.get("DEPLOYMENT_STATUS")
        or "Successful"
    )
    message = (
        metadata.get("deployment_message")
        or os.environ.get("DEPLOYMENT_MESSAGE")
        or DEFAULT_MESSAGE
    )
    raw_timestamp = (
        metadata.get("deployment_timestamp_utc")
        or os.environ.get("DEPLOYMENT_TIMESTAMP_UTC")
    )
    commit = (
        metadata.get("deployment_commit")
        or os.environ.get("DEPLOYMENT_COMMIT")
        or "0bf459f"
    )
    commit_msg = metadata.get("deployment_commit_message")
    if commit_msg is None:
        commit_msg = (
            os.environ.get("DEPLOYMENT_COMMIT_MESSAGE")
            or "feat(infra): complete Phase 1-5 AWS, Puppet 8, and CI/CD deployment pipeline"
        )
    image_tag = (
        metadata.get("deployment_image_tag")
        or os.environ.get("DEPLOYMENT_IMAGE_TAG")
        or f"sha-{commit[:7]}"
    )
    pipeline = (
        metadata.get("deployment_pipeline")
        or DEFAULT_PIPELINE
    )
    deployment_path = (
        metadata.get("deployment_path")
        or DEFAULT_PATH
    )
    workflow_run = (
        metadata.get("deployment_workflow_run")
        or os.environ.get("DEPLOYMENT_WORKFLOW_RUN")
        or "production"
    )

    formatted_ist, raw_utc = parse_timestamp_to_ist(raw_timestamp)
    is_confirmed = status.strip().lower() == "successful"

    return {
        "status": status,
        "message": message,
        "pipeline": pipeline,
        "deployment_path": deployment_path,
        "timestamp_ist": formatted_ist,
        "timestamp_utc": raw_utc,
        "commit": commit[:7] if commit else "unknown",
        "commit_message": commit_msg,
        "image_tag": image_tag,
        "workflow_run": str(workflow_run),
        "is_confirmed": is_confirmed,
    }
